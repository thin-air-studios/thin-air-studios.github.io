// Cloudflare Pages' /_headers and /_redirects (at the repository root, where the host reads them). Generated from the pages the
// other modules made, so the list of sections follows the site as it grows.
//   - Security headers on every path: HSTS, nosniff, Referrer-Policy.
//   - A Content-Security-Policy only on the website's own pages (the home, and every section the build makes). The browser demo,
//     the legal pages, the play page and the map and route folders are not under it: they are built elsewhere and call services
//     this policy does not list. Script hashes come from the inline scripts the layout writes (the Google Analytics bootstrap).
//   - Long cache for /assets/site/fonts, img and og (1 year); a day, with a week of stale-while-revalidate, for css, js and json,
//     so a stylesheet change reaches returning visitors within a day.
// Redirects: the old sitemap name, kept for links and Search Console.
import crypto from 'node:crypto';


export const order = 950;

const LINE_LIMIT = 2000;

function inlineScriptHashes(outputs) {
  const hashes = new Set();
  for (const o of outputs) {
    if (o.meta.kind !== 'html' || typeof o.bytes !== 'string') continue;
    for (const [, body] of o.bytes.matchAll(/<script>([\s\S]*?)<\/script>/g)) {
      hashes.add(`'sha256-${crypto.createHash('sha256').update(body, 'utf8').digest('base64')}'`);
    }
  }
  return [...hashes].sort();
}

function policy(config, hashes) {
  const ga = Boolean(config.analytics?.ga4);
  const cf = Boolean(config.analytics?.cfBeacon);
  const script = ["'self'", ...hashes];
  if (ga) script.push('https://www.googletagmanager.com');
  if (cf) script.push('https://static.cloudflareinsights.com');
  const connect = ["'self'"];
  if (ga) connect.push('https://www.google-analytics.com', 'https://*.google-analytics.com', 'https://*.analytics.google.com', 'https://www.googletagmanager.com');
  if (cf) connect.push('https://cloudflareinsights.com');
  const img = ["'self'"];
  if (ga) img.push('https://www.google-analytics.com', 'https://www.googletagmanager.com');
  return [
    "default-src 'self'",
    `script-src ${script.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    `img-src ${img.join(' ')}`,
    "font-src 'self'",
    `connect-src ${connect.join(' ')}`,
    'frame-src https://www.youtube-nocookie.com',
    "media-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/** The path patterns of the website's own pages: '/', each top-level section ('/airports/*'), and each page file. */
function sitePatterns(outputs) {
  const patterns = new Set();
  for (const o of outputs) {
    if (o.meta.kind !== 'html') continue;
    const p = o.meta.path;
    if (p === '/') patterns.add('/');
    else if (p.endsWith('.html')) patterns.add(p);
    else patterns.add(`/${p.split('/')[1]}/*`);
  }
  return [...patterns].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export async function pages(ctx) {
  const { config } = ctx;
  const outputs = ctx.previous;
  const hashes = inlineScriptHashes(outputs);
  const csp = policy(config, hashes);
  const lines = [
    '# Cloudflare Pages headers for the website (generated by tools/site/pages/headers.mjs; do not edit by hand).',
    '',
    '/*',
    '  Strict-Transport-Security: max-age=31536000',
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '',
  ];
  for (const pattern of sitePatterns(outputs)) {
    lines.push(pattern, `  Content-Security-Policy: ${csp}`, '');
  }
  lines.push(
    '/assets/site/fonts/*',
    '  Cache-Control: public, max-age=31536000',
    '/assets/site/img/*',
    '  Cache-Control: public, max-age=31536000',
    '/assets/site/og/*',
    '  Cache-Control: public, max-age=31536000',
    '/assets/site/*',
    '  Cache-Control: public, max-age=86400, stale-while-revalidate=604800',
    '',
  );
  const headers = lines.join('\n');
  for (const line of headers.split('\n')) {
    if (line.length > LINE_LIMIT) throw new Error(`_headers line longer than ${LINE_LIMIT} characters`);
  }
  const redirects = [
    '# Cloudflare Pages redirects (generated by tools/site/pages/headers.mjs).',
    '/sitemap-home.xml /sitemaps/pages.xml 301',
    '',
  ].join('\n');
  return [
    { path: '/_headers', content: headers },
    { path: '/_redirects', content: redirects },
  ];
}


